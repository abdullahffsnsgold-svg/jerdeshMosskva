-- ---------- 1. Пользователи (телефон + пароль) ----------
create table if not exists public.users (
  id          bigint generated by default as identity primary key,
  phone       text not null unique,          -- только цифры: 996555123456
  password    text not null,
  created_at  timestamptz not null default now()
);

-- ---------- 2. Категории ----------
create table if not exists public.categories (
  id    bigint generated by default as identity primary key,
  name  text not null
);

-- ---------- 3. Объявления ----------
create table if not exists public.products (
  id               bigint generated by default as identity primary key,
  title            text not null,
  description      text,
  price            numeric(12, 2) not null default 0,
  category_id      bigint references public.categories (id) on delete set null,
  location         text,
  customer_name    text,
  customer_number  text,
  image_url        text,
  views            integer not null default 0,
  created_at       timestamptz not null default now()
);

create index if not exists products_created_at_idx on public.products (created_at desc);
create index if not exists products_category_id_idx on public.products (category_id);

-- ---------- 4. Комментарии к объявлениям ----------
create table if not exists public.comments (
  id          bigint generated by default as identity primary key,
  product_id  bigint not null references public.products (id) on delete cascade,
  text        text not null,
  username    text default 'Гость',
  created_at  timestamptz not null default now()
);

create index if not exists comments_product_id_created_at_idx
  on public.comments (product_id, created_at desc);

-- ---------- 5. Сторис ----------
create table if not exists public.user_stories (
  id               bigint generated by default as identity primary key,
  title            text,
  text             text,
  media_url        text not null,
  media_type       text not null default 'image'
                   check (media_type in ('image', 'video')),
  customer_number  text,
  user_id          bigint references public.users (id) on delete set null,
  created_at       timestamptz not null default now()
);

create index if not exists user_stories_created_at_idx
  on public.user_stories (created_at desc);

-- ---------- 6. Стартовые категории (их же показывает поиск на главной) ----------
insert into public.categories (name)
select v.name
from (values ('Работа'), ('Жилье'), ('Услуги'), ('Продажа авто'), ('Вещи / Электроника')) as v(name)
where not exists (select 1 from public.categories c where c.name = v.name);

-- =========================================================
--  RLS
--  Таблица users намеренно НЕ получает публичных политик: доступ к ней
--  идёт только через RPC-функции из supabase/secure-users.sql
--  (обязательно выполните его после этого файла).
--  Остальные таблицы пока открыты, потому что приложение работает
--  с anon-ключом.
-- =========================================================
alter table public.users        enable row level security;
alter table public.categories   enable row level security;
alter table public.products     enable row level security;
alter table public.comments     enable row level security;
alter table public.user_stories enable row level security;

-- users: политик нет — таблица закрыта, работа идёт через RPC

-- categories: только чтение
drop policy if exists "categories_select_public" on public.categories;
create policy "categories_select_public" on public.categories
  for select to anon, authenticated using (true);

-- products: чтение, создание и обновление счётчика просмотров
drop policy if exists "products_select_public" on public.products;
create policy "products_select_public" on public.products
  for select to anon, authenticated using (true);

drop policy if exists "products_insert_public" on public.products;
create policy "products_insert_public" on public.products
  for insert to anon, authenticated with check (true);

drop policy if exists "products_update_public" on public.products;
create policy "products_update_public" on public.products
  for update to anon, authenticated using (true) with check (true);

-- comments: чтение и добавление (.select().single() после insert требует select-политику)
drop policy if exists "comments_select_public" on public.comments;
create policy "comments_select_public" on public.comments
  for select to anon, authenticated using (true);

drop policy if exists "comments_insert_public" on public.comments;
create policy "comments_insert_public" on public.comments
  for insert to anon, authenticated with check (true);

-- user_stories: чтение и создание
drop policy if exists "stories_select_public" on public.user_stories;
create policy "stories_select_public" on public.user_stories
  for select to anon, authenticated using (true);

drop policy if exists "stories_insert_public" on public.user_stories;
create policy "stories_insert_public" on public.user_stories
  for insert to anon, authenticated with check (true);

-- =========================================================
--  Storage: публичные бакеты для фото объявлений и сторис
-- =========================================================
insert into storage.buckets (id, name, public)
values ('products', 'products', true)
on conflict (id) do update set public = excluded.public;

insert into storage.buckets (id, name, public)
values ('stories', 'stories', true)
on conflict (id) do update set public = excluded.public;

drop policy if exists "products_bucket_read" on storage.objects;
create policy "products_bucket_read" on storage.objects
  for select to anon, authenticated using (bucket_id = 'products');

drop policy if exists "products_bucket_upload" on storage.objects;
create policy "products_bucket_upload" on storage.objects
  for insert to anon, authenticated with check (bucket_id = 'products');

drop policy if exists "stories_bucket_read" on storage.objects;
create policy "stories_bucket_read" on storage.objects
  for select to anon, authenticated using (bucket_id = 'stories');

drop policy if exists "stories_bucket_upload" on storage.objects;
create policy "stories_bucket_upload" on storage.objects
  for insert to anon, authenticated with check (bucket_id = 'stories');
